function slugify(text) {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function parseLegalDocument(markdown) {
  const blocks = [];
  const toc = [];
  let listItems = null;

  function flushList() {
    if (!listItems) return;
    blocks.push({ type: 'ul', items: listItems });
    listItems = null;
  }

  markdown.split('\n').forEach((line) => {
    if (line === '') {
      flushList();
      return;
    }

    if (line === '---') {
      flushList();
      blocks.push({ type: 'hr' });
      return;
    }

    if (line.startsWith('# ')) {
      flushList();
      const text = line.slice(2);
      const id = slugify(text);
      const block = { type: 'h1', text, id };
      blocks.push(block);
      if (/^\d+\./.test(text)) toc.push(block);
      return;
    }

    if (line.startsWith('## ')) {
      flushList();
      blocks.push({ type: 'h2', text: line.slice(3), id: slugify(line.slice(3)) });
      return;
    }

    if (line.startsWith('* ')) {
      if (!listItems) listItems = [];
      listItems.push(line.slice(2));
      return;
    }

    flushList();
    blocks.push({ type: 'p', text: line });
  });

  flushList();
  return { blocks, toc };
}

